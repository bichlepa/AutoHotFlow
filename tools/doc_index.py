#!/usr/bin/env python
"""Document index: writes doc/DOC-INDEX.md, a map of the large documents with line ranges.

An agent greps doc/DOC-INDEX.md for a keyword and then reads only the lines of the hit (Read with offset and
limit). Every section of a listed document is one line, "L<first>-<last> <heading text>". The last line of a
section is the line before the next heading of the same or a higher level (or the end of the file); trailing
blank lines do not count. A line inside a fenced code block is never a heading.

The documents are listed in the constants at the top of this file: HEADING_DOCS (heading levels per document),
HOWTO_DIR (the entries of the how-to knowledge base, with their status) and ID_DOCS (documents whose entries
are found by ID; only a line about how to find them). The index is never edited by hand.

Usage:  python tools/doc_index.py            write doc/DOC-INDEX.md
        python tools/doc_index.py --check    check that doc/DOC-INDEX.md is up to date (exit 1 if not)
"""

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
INDEX = REPO / "doc" / "DOC-INDEX.md"

# Documents whose section headings are listed: path -> heading levels.
HEADING_DOCS = {
    "doc/ARCHITECTURE.md": (2, 3),
    "doc/PROTOCOL.md": (2, 3),
    "doc/TEST-STRATEGY.md": (2, 3),
    "doc/ELEMENT-API-V2.md": (2, 3),
    "doc/EXPRESSION-LANGUAGE.md": (2, 3),
    "doc/MEASUREMENTS.md": (2, 3),
    "doc/CONVENTIONS.md": (2, 3),
}

# The how-to category files: every entry (### heading) with the status of its Status line.
HOWTO_DIR = "doc/howto"
HOWTO_LEVELS = (3,)

# Documents with IDs: one line on how to find an entry, no section list.
ID_DOCS = {
    "doc/REQUIREMENTS.md": "Entries are `### REQ-<AREA>-<NNN> <title>`. Find one by its ID, e.g. "
                           "`grep -n REQ-ELM-240 doc/REQUIREMENTS.md`. Overview: `doc/REQUIREMENTS-INDEX.md`.",
    "doc/OPEN-ITEMS.md": "Open findings `F-<NNNN>`: one row each in the summary table at the top, one entry each "
                         "below. Find one with `grep -n F-0097 doc/OPEN-ITEMS.md`.",
    "doc/CLOSED-ITEMS.md": "Closed and accepted findings `F-<NNNN>`: one row each in the table at the top. "
                           "Find one with `grep -n F-0011 doc/CLOSED-ITEMS.md`.",
    "doc/DECISIONS.md": "Owner decisions `E<NNNN>`: one row each in the table. "
                        "Find one with `grep -n E0035 doc/DECISIONS.md`.",
    "doc/MIGRATION.md": "Deliberate deviations from v1 `M-<NNNN>`: one row each in the table. "
                        "Find one with `grep -n M-0059 doc/MIGRATION.md`.",
}

HEADER = [
    "# Document index",
    "",
    "Generated by tools/doc_index.py, do not edit. Use: grep this file for a keyword, then read the lines of the hit.",
    "",
]

HEADING = re.compile(r"^(#{1,6}) (\S.*?)\s*$")
FENCE = re.compile(r"^\s*```")
STATUS = re.compile(r"^- \*\*Status:\*\* (.*)$")


def headings(lines):
    """Return (line number, level, text) of every heading, 1-based, outside fenced code blocks."""
    found = []
    fenced = False
    for number, line in enumerate(lines, start=1):
        if FENCE.match(line):
            fenced = not fenced
            continue
        if fenced:
            continue
        m = HEADING.match(line)
        if m:
            found.append((number, len(m.group(1)), m.group(2)))
    return found


def sections(lines, levels):
    """Return (first, last, level, text) for every heading whose level is in levels.

    The section ends before the next heading of the same or a higher level, or at the end of the file.
    Trailing blank lines are not part of the range.
    """
    all_heads = headings(lines)
    result = []
    for index, (number, level, text) in enumerate(all_heads):
        if level not in levels:
            continue
        end = len(lines)
        for next_number, next_level, _ in all_heads[index + 1:]:
            if next_level <= level:
                end = next_number - 1
                break
        last = number
        for line_number in range(end, number, -1):
            if lines[line_number - 1].strip():
                last = line_number
                break
        result.append((number, last, level, text))
    return result


def entry_status(lines, first, last):
    """Status word of a how-to entry, derived from its Status line (same rule as the first index)."""
    for line in lines[first - 1:last]:
        m = STATUS.match(line)
        if not m:
            continue
        s = m.group(1)
        verified = "verified" in s
        assumed = "assumed" in s
        not_checked = "not checked" in s or "not investigated" in s
        if s.startswith("observed once"):
            return "not checked"
        if verified and (assumed or not_checked):
            return "partly verified"
        if verified:
            return "verified"
        if assumed:
            return "assumed"
        if not_checked:
            return "not checked"
        raise ValueError("unknown status: " + s[:60])
    raise ValueError("entry without a Status line: " + lines[first - 1][:60])


def read(path):
    text = path.read_text(encoding="utf-8")
    lines = text.split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    return text, lines


def size_line(path, lines):
    size_kb = round(path.stat().st_size / 1024, 1)
    return "## %s (%.1f KB, %d lines)" % (path.relative_to(REPO).as_posix(), size_kb, len(lines))


def section_lines(items, base_level):
    out = []
    for first, last, level, text in items:
        indent = "  " * (level - base_level)
        out.append("L%d-%d %s%s" % (first, last, indent, text))
    return out


def build():
    out = list(HEADER)
    for rel, levels in HEADING_DOCS.items():
        path = REPO / rel
        _, lines = read(path)
        out.append(size_line(path, lines))
        out.append("```text")
        out += section_lines(sections(lines, levels), min(levels))
        out.append("```")
        out.append("")
    for path in sorted((REPO / HOWTO_DIR).glob("*.md")):
        _, lines = read(path)
        out.append(size_line(path, lines))
        out.append("```text")
        for first, last, level, text in sections(lines, HOWTO_LEVELS):
            out.append("L%d-%d %s (%s)" % (first, last, text, entry_status(lines, first, last)))
        out.append("```")
        out.append("")
    for rel, how in ID_DOCS.items():
        path = REPO / rel
        _, lines = read(path)
        out.append(size_line(path, lines))
        out.append(how)
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description="Write or check doc/DOC-INDEX.md.")
    parser.add_argument("--check", action="store_true", help="only check that the index is up to date")
    args = parser.parse_args(argv)
    try:
        text = build()
    except (ValueError, OSError) as error:
        print("doc_index: %s" % error, file=sys.stderr)
        return 1
    current = INDEX.read_text(encoding="utf-8") if INDEX.exists() else ""
    if args.check:
        if current != text:
            print("doc/DOC-INDEX.md is outdated: run python tools/doc_index.py", file=sys.stderr)
            return 1
        print("doc/DOC-INDEX.md is up to date")
        return 0
    with open(INDEX, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    print("written %s (%.1f KB)" % (INDEX.relative_to(REPO).as_posix(), len(text.encode("utf-8")) / 1024))
    return 0


if __name__ == "__main__":
    sys.exit(main())
